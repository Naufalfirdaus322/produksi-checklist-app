-- =========================================================================
-- PT. BERKAT CAHAYA NOVENA - SISTEM CHECKLIST & OPERASIONAL PRODUKSI
-- Database Schema & Seed Data untuk Supabase (PostgreSQL)
-- =========================================================================

-- 1. Hapus tabel jika sudah ada (opsional / reset)
DROP TABLE IF EXISTS checklist_entries CASCADE;
DROP TABLE IF EXISTS checklists CASCADE;
DROP TABLE IF EXISTS room_items CASCADE;
DROP TABLE IF EXISTS rooms CASCADE;
DROP TABLE IF EXISTS notifications CASCADE;

-- 2. Buat Tabel Rooms (Master Ruang Produksi & SOP Dokumen)
CREATE TABLE rooms (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    code TEXT NOT NULL,
    revision TEXT NOT NULL,
    effective_date TEXT NOT NULL,
    building TEXT NOT NULL,
    display_order INT DEFAULT 1
);

-- 3. Buat Tabel Room Items (Aspek Kebersihan & Peralatan)
CREATE TABLE room_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id TEXT REFERENCES rooms(id) ON DELETE CASCADE,
    item_no INT NOT NULL,
    name TEXT NOT NULL,
    category TEXT DEFAULT 'Peralatan'
);

-- 4. Buat Tabel Checklists (Laporan Harian per Shift)
CREATE TABLE checklists (
    id TEXT PRIMARY KEY,
    room_id TEXT REFERENCES rooms(id) ON DELETE CASCADE,
    check_date DATE NOT NULL,
    shift TEXT NOT NULL,
    operator_name TEXT,
    leader_name TEXT,
    operator_signature TEXT,
    leader_signature TEXT,
    is_verified_by_leader BOOLEAN DEFAULT FALSE,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Buat Tabel Checklist Entries (Detail Kondisi & Kebersihan Tiap Item)
CREATE TABLE checklist_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checklist_id TEXT REFERENCES checklists(id) ON DELETE CASCADE,
    item_id BIGINT,
    item_name TEXT NOT NULL,
    condition_status TEXT NOT NULL DEFAULT 'baik', -- 'baik' (√) atau 'rusak' (×)
    clean_status TEXT NOT NULL DEFAULT 'bersih',   -- 'bersih' (√) atau 'kotor' (×)
    corrective_action TEXT,
    damaged_count INT DEFAULT 0,
    reported_to_leader BOOLEAN DEFAULT FALSE,
    is_resolved BOOLEAN DEFAULT FALSE,
    resolved_at TIMESTAMPTZ,
    resolved_by TEXT
);

-- 6. Buat Tabel Notifications (Pengingat & Peringatan Kerusakan)
CREATE TABLE notifications (
    id TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    type TEXT DEFAULT 'info', -- 'info', 'warning', 'reminder', 'urgent'
    room_id TEXT,
    is_read BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- =========================================================================
-- KEAMANAN & AKSES (Row Level Security - RLS)
-- Izinkan akses baca dan tulis untuk staf operator & leader via Anon Key
-- =========================================================================

ALTER TABLE rooms ENABLE ROW LEVEL SECURITY;
ALTER TABLE room_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE checklists ENABLE ROW LEVEL SECURITY;
ALTER TABLE checklist_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Akses Publik Rooms" ON rooms FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Akses Publik Room Items" ON room_items FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Akses Publik Checklists" ON checklists FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Akses Publik Checklist Entries" ON checklist_entries FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Akses Publik Notifications" ON notifications FOR ALL USING (true) WITH CHECK (true);

-- =========================================================================
-- AKTIFKAN REALTIME SINKRONISASI SUPABASE (WebSockets)
-- =========================================================================

ALTER PUBLICATION supabase_realtime ADD TABLE checklists;
ALTER PUBLICATION supabase_realtime ADD TABLE checklist_entries;
ALTER PUBLICATION supabase_realtime ADD TABLE notifications;

